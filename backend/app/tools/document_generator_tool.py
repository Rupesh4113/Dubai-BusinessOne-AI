"""Document & Report Generation Tool."""

import json
from datetime import datetime, timezone
from typing import Dict, Any
from .base import BaseTool, ToolResult


class DocumentGeneratorTool(BaseTool):
    name = "document_generator"
    description = "Generates formatted operational dossiers, statutory compliance summaries, and exportable PDF/Markdown reports."
    risk_level = "LOW"
    requires_approval = False

    def run(self, params: Dict[str, Any], context: Dict[str, Any]) -> ToolResult:
        doc_type = params.get("document_type", "SETUP_DOSSIER")
        title = params.get("title", "Dubai Business Operations Report")
        sections = params.get("sections", {})
        financial_summary = params.get("financial_summary", {})
        citations = params.get("citations", [])
        now_str = datetime.now(timezone.utc).strftime("%d %B %Y %H:%M UTC")

        # Build clean Markdown document
        md_lines = [
            f"# {title}",
            f"**Generated by**: Dubai BusinessOne AI — Intelligent Digital Operations Agent  ",
            f"**Timestamp**: {now_str}  ",
            f"**Jurisdiction**: Dubai, United Arab Emirates  ",
            "---",
            "## 1. Executive Summary",
            sections.get("summary", "Automated operational dossier prepared for Dubai commercial operations."),
            ""
        ]

        if "licensing_details" in sections:
            md_lines.extend([
                "## 2. Licensing & Regulatory Structure",
                sections["licensing_details"],
                ""
            ])

        if financial_summary:
            md_lines.extend([
                "## 3. Statutory Financial & Fee Breakdown",
                "| Fee / Tax Item | Statutory Authority | Amount (AED) | Reference Law |",
                "|:---|:---|:---|:---|"
            ])
            for item in financial_summary.get("items", []):
                md_lines.append(f"| {item.get('name', 'Fee')} | {item.get('authority', 'DET')} | AED {item.get('amount', '0.00')} | {item.get('reference', 'Statutory')} |")

            total_aed = financial_summary.get("total_aed", "0.00")
            md_lines.extend([
                f"| **Total Consolidated Amount** | **Official Government Vouchers** | **AED {total_aed}** | **Verified Schedule** |",
                ""
            ])

        if citations:
            md_lines.extend([
                "## 4. Authoritative Legal Citations & Sources",
                "Every regulation and fee has been verified against official UAE government portals:",
                ""
            ])
            for cit in citations:
                md_lines.append(f"- **[{cit.get('citation_id', 'CIT')}] {cit.get('authority_name')}**: {cit.get('statutory_law')} ([Source Portal]({cit.get('official_source_url')}))")
            md_lines.append("")

        md_content = "\n".join(md_lines)

        return ToolResult(
            tool_name=self.name,
            success=True,
            data={
                "document_title": title,
                "document_type": doc_type,
                "generated_timestamp": now_str,
                "markdown_content": md_content,
                "word_count": len(md_content.split())
            },
            audit_trail=[f"Generated formal document '{title}' ({doc_type})"]
        )

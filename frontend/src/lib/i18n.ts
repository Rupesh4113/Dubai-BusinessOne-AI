/**
 * Safe translation resolver with graceful fallback to English and key name.
 */
export function t(key: string, lang: LanguageCode = "en"): string {
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en?.[key] || key;
}

/**
 * Safe text direction helper ('rtl' for Arabic and Urdu; 'ltr' for others).
 */
export function getLanguageDirection(lang: LanguageCode = "en"): "rtl" | "ltr" {
  return LANGUAGES[lang]?.dir || "ltr";
}
